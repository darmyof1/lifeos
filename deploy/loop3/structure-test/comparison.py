#!/usr/bin/env python3
"""comparison.py - builds ~/handover/structure-test/comparison/comparison.md from the stored per-run result files (APR-0099).
4-set runs: loop3-reg-001..003 (baseline, scored with the ack rule as in rescore.md; metrics recomputed from the exports) and loop3-cmp-001..003 (comparison dir).
Solo runs: loop3-cmp-s-*. Shared criteria and 4-set-only criteria are scored separately and never mixed."""
import glob, json, os, re, subprocess, sys, datetime
H = os.path.expanduser("~/handover"); CMP = H + "/structure-test/comparison"
SC = [("R", "bad-sleep"), ("D1", "D1 delete (CEO instruction)"), ("D2", "D2 delete (CEO question, approval)"), ("D3", "D3 delete asked by a chief"), ("C", "CFO entry"), ("O", "overlap"), ("P", "privacy request")]
JOBDEP = ("numstat after the job", "numstat 5 0 then 6 0", "Google shows busy", "the job deleted", "Google event is still there")
def code_of(name):
    n = name.lower()
    return ("R" if "bad-sleep" in n else "D1" if "d1" in n else "D2" if "d2" in n else "D3" if "d3" in n else "C" if "cfo" in n else "O" if "overlap" in n else "P")
def is4only(x):
    return ("sessions_send checker" in x or "names the CHO and the CoS" in x or "called the CoS itself" in x or "requested by CHO" in x)
runs = []   # dicts: variant, scn, run, shared_fail, only4_fail, ack, notscorable, cost, metrics
def parse(f, variant, baseline=False):
    t = open(f).read()
    if "-- criteria" not in t: return
    run = os.path.basename(f)[:-4]; hdr = re.search(r"== \S+\s+(.*?)\s+(\d{4}-\d\d-\d\d \d\d:\d\d) AST", t)
    if variant == "solo":
        hdr = re.search(r"== \S+\s+solo\s+(\S+)\s+(\d{4}-\d\d-\d\d \d\d:\d\d) AST", t); scn = code_of(hdr.group(1))
    else: scn = code_of(hdr.group(1))
    crit = t.split("-- criteria")[1].split("-- cost")[0].strip().splitlines()
    ack = bool(re.search(r"ack error seen", t)) or bool(re.search(r"^FAIL\s+no SESSION_WORK_START_CHANGED", t, re.M))
    jobnot = "job not run" in t or "journal checks failed, job not run" in t
    sh, o4, ns = [], [], []
    for c in crit:
        if c.startswith("INFO") or c.startswith("4-SET-ONLY"): continue
        ok = c.startswith("PASS"); x = c[5:]
        if ok: continue
        if "sessions_send checker" in x and ack: continue
        if ack and jobnot and any(k in x for k in JOBDEP): ns.append(x); continue
        if scn == "C" and variant == "4set" and "event ID" in x and "-cfo-01" in x:   # mixed line: re-judge the shared part from the stored journal lines
            jl = [l for l in t.split("-- journal lines for")[1].split("-- check output")[0].splitlines() if " | written | " in l]
            shared_ok = len(jl) == 1 and jl[0].startswith("CFO - ") and "privacy=high" in jl[0]
            if not shared_ok: sh.append("CFO line: title/privacy/exactly one")
            if not (jl and ("-cfo-01" in jl[0] and jl[0].split("|")[6].strip() == "CFO")): o4.append("CFO event ID name or requested by CFO")
            continue
        (o4 if is4only(x) else sh).append(x)
    m = re.search(r"-- cost: \S+ total ([0-9.]+) USD", t)
    runs.append({"variant": variant, "scn": scn, "run": run, "shared_fail": sh, "only4_fail": o4, "ack": ack, "notscorable": ns, "cost": float(m.group(1)) if m else 0.0,
                 "start": hdr.group(2) if variant != "solo" else hdr.group(2), "file": f})
for f in sorted(glob.glob(H + "/regression/loop3-reg-00?/loop3-reg-00?-0?.txt")): parse(f, "4set", True)
for f in sorted(glob.glob(CMP + "/loop3-cmp-00?/loop3-cmp-00?-0?.txt")): parse(f, "4set")
for f in sorted(glob.glob(CMP + "/loop3-cmp-s-*.txt")): parse(f, "solo")
# metrics
def metrics(r):
    mj = os.path.splitext(r["file"])[0] + ".metrics.json"
    if r["run"].startswith("loop3-reg-"):
        ag = ["coo", "cho", "cos"] + (["cfo"] if r["scn"] == "C" else [])
        if r["scn"] == "D3": ag = ["cho", "cos"]
        dt = datetime.datetime.strptime(r["start"], "%Y-%m-%d %H:%M") + datetime.timedelta(hours=4)
        out = subprocess.run(["python3", os.path.expanduser("~/loop1/run-metrics.py"), r["run"], dt.strftime("%Y-%m-%dT%H:%M:00Z")] + ag, capture_output=True, text=True).stdout.strip().splitlines()
        try: d = json.loads(out[-1]); d["wall_s"] = None; return d
        except Exception: return None
    try: return json.load(open(mj))
    except Exception: return None
for r in runs: r["m"] = metrics(r)
def n_pass(rs, key): return sum(1 for r in rs if not r[key])
L = ["# Structure comparison: one agent (solo) against the four-agent set (COO, CHO, CoS, CFO)", "",
     "Generated by comparison.py from the per-run files in this folder and in regression/ (baseline loop3-reg-001 to -003, re-scored with the ack rule of APR-0099). Measures reliability on seven synthetic scenarios; it does NOT measure data-scope isolation (ADR-0016, APR-0086) and cannot alone justify merging agents. Nothing here recommends a structure change.", ""]
L += ["## 1. Pass counts per scenario (shared criteria)", "",
      "A run passes when none of its shared criteria failed. Criteria that failed only because the old runner did not run the job after an acknowledgement error are not scored (listed in section 2).", "",
      "| scenario | 4-set shared pass | solo shared pass | 4-set runs | solo runs |", "|---|---|---|---|---|"]
for c, name in SC:
    a = [r for r in runs if r["variant"] == "4set" and r["scn"] == c]; b = [r for r in runs if r["variant"] == "solo" and r["scn"] == c]
    L.append("| %s | %d/%d | %d/%d | %d | %d |" % (name, n_pass(a, "shared_fail"), len(a), n_pass(b, "shared_fail"), len(b), len(a), len(b)))
ta = [r for r in runs if r["variant"] == "4set"]; tb = [r for r in runs if r["variant"] == "solo"]
L.append("| **all** | **%d/%d** | **%d/%d** | %d | %d |" % (n_pass(ta, "shared_fail"), len(ta), n_pass(tb, "shared_fail"), len(tb), len(ta), len(tb)))
L += ["", "## 2. 4-set only faults (not comparable: solo has no hand-offs)", "", "| scenario | runs with a 4-set-only fault | acknowledgement errors seen | criteria not scorable (job did not run) |", "|---|---|---|---|"]
for c, name in SC:
    a = [r for r in runs if r["variant"] == "4set" and r["scn"] == c]
    L.append("| %s | %d/%d | %d | %d |" % (name, sum(1 for r in a if r["only4_fail"]), len(a), sum(1 for r in a if r["ack"]), sum(len(r["notscorable"]) for r in a)))
L += ["", "## 3. Failures exactly as they happened (shared criteria)", ""]
for r in runs:
    if r["shared_fail"]: L.append("- %s (%s, %s): %s" % (r["run"], r["variant"], r["scn"], "; ".join(r["shared_fail"])))
for r in runs:
    if r["only4_fail"]: L.append("- %s (4-set only, %s): %s" % (r["run"], r["scn"], "; ".join(r["only4_fail"])))
L += ["", "## 4. Cost, tokens, turns, prompt size (means per run)", "", "| variant | runs | mean cost USD | total cost USD | mean input | mean output | mean cacheRead | mean turns | mean tool calls | mean wall s | mean first-turn tokens (sum over agents that ran) | mean instruction bytes (agents that ran) |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for v, rs in (("4-set", ta), ("solo", tb)):
    ms = [r["m"] for r in rs if r["m"]]; k = max(1, len(ms))
    f = lambda key: sum(m["total"][key] for m in ms) / k
    walls = [m["wall_s"] for m in ms if m.get("wall_s")]
    L.append("| %s | %d | %.4f | %.4f | %.0f | %.0f | %.0f | %.1f | %.1f | %s | %.0f | %.0f |" % (v, len(rs), sum(r["cost"] for r in rs) / max(1, len(rs)), sum(r["cost"] for r in rs), f("input"), f("output"), f("cacheRead"), f("turns"), f("tool_calls"), ("%.0f" % (sum(walls) / len(walls)) if walls else "n/a"), f("first_turn_tokens"), f("instr_bytes")))
L += ["", "Wall time is measured for the new runs only (the baseline suites did not record it). Instruction bytes: the four live files of each agent that ran in the run; the full sets are 4-set about 25 KB over four agents (COO, CHO, CoS, CFO) and solo 9072 bytes.", "",
      "## 5. Per scenario means", "", "| scenario | variant | mean cost USD | mean turns | mean tool calls | mean output tokens |", "|---|---|---|---|---|---|"]
for c, name in SC:
    for v in ("4set", "solo"):
        rs = [r for r in runs if r["variant"] == v and r["scn"] == c and r["m"]]
        if rs:
            k = len(rs); L.append("| %s | %s | %.4f | %.1f | %.1f | %.0f |" % (name, v, sum(r["cost"] for r in rs) / k, sum(r["m"]["total"]["turns"] for r in rs) / k, sum(r["m"]["total"]["tool_calls"] for r in rs) / k, sum(r["m"]["total"]["output"] for r in rs) / k))
L += ["", "## 6. Every run", "", "| run | variant | scenario | shared | 4-set only | ack | cost |", "|---|---|---|---|---|---|---|"]
for r in runs:
    L.append("| %s | %s | %s | %s | %s | %s | %.4f |" % (r["run"], r["variant"], r["scn"], "PASS" if not r["shared_fail"] else "FAIL", ("fault" if r["only4_fail"] else "-") if r["variant"] == "4set" else "n/a", "yes" if r["ack"] else "-", r["cost"]))
open(CMP + "/comparison.md", "w").write("\n".join(L) + "\n"); print("\n".join(L[:30]))
